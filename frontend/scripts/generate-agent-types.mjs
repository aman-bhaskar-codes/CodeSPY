/* global process, console */
// Generates src/features/agent/protocol/types.gen.ts from docs/contracts/AgentEventV1.schema.json.
// `node scripts/generate-agent-types.mjs --check` fails when the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { format, resolveConfig } from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(
  here,
  "../../docs/contracts/AgentEventV1.schema.json",
);
const target = resolve(here, "../src/features/agent/protocol/types.gen.ts");

// Pydantic titles every property ("Seq", "Type", ...), which would become top-level aliases.
// Only models (objects with properties) keep their title: they become the named interfaces.
function untitle(node) {
  if (Array.isArray(node)) return node.map(untitle);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && typeof value === "string" && !("properties" in node))
      continue;
    out[key] = untitle(value);
  }
  return out;
}

const schema = untitle(JSON.parse(readFileSync(schemaPath, "utf8")));
const types = Object.keys(schema.payloads);

// One object whose properties are the payload of each event type, keyed by type name.
const payloads = {
  title: "AgentEventPayloads",
  type: "object",
  additionalProperties: false,
  required: types,
  properties: schema.payloads,
  $defs: schema.$defs,
};
const envelope = {
  ...schema.envelope,
  title: "AgentEventEnvelope",
  $defs: schema.$defs,
};

const options = {
  bannerComment: "",
  additionalProperties: false,
  unreachableDefinitions: false,
  strictIndexSignatures: true,
  format: false,
};

let body = "";
body += await compile(envelope, "AgentEventEnvelope", options);
body += await compile(payloads, "AgentEventPayloads", options);

const raw = `// Generated by scripts/generate-agent-types.mjs from docs/contracts/AgentEventV1.schema.json.
// Do not edit by hand: change the backend contract, then run \`npm run codegen:agent\`.

export const AGENT_PROTOCOL_VERSION = ${schema.protocol_version} as const;
export const TRANSIENT_EVENT_TYPES = ${JSON.stringify(schema.transient_types)} as const;
export const AGENT_EVENT_TYPES = ${JSON.stringify(types)} as const;

${body}
export type AgentEventType = keyof AgentEventPayloads;

/** An event of a type this client knows, with its payload typed. */
export type KnownAgentEvent = {
  [K in AgentEventType]: Omit<AgentEventEnvelope, "type" | "payload"> & {
    type: K;
    payload: AgentEventPayloads[K];
  };
}[AgentEventType];

/** An event of a type added after this client was built. Clients ignore these. */
export type UnknownAgentEvent = Omit<AgentEventEnvelope, "payload"> & {
  payload: { [k: string]: unknown };
};

export type AgentEvent = KnownAgentEvent | UnknownAgentEvent;
`;

const out = await format(raw, {
  ...(await resolveConfig(target)),
  parser: "typescript",
});

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing file counts as out of date
  }
  if (current !== out) {
    console.error("types.gen.ts is out of date: run `npm run codegen:agent`");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
}
